DROP TABLE IF EXISTS app_session CASCADE;
DROP TABLE IF EXISTS app_notification CASCADE;
DROP TABLE IF EXISTS activity_history CASCADE;
DROP TABLE IF EXISTS library_entries CASCADE;
DROP TABLE IF EXISTS anilist_connection CASCADE;
DROP TABLE IF EXISTS app_user CASCADE;

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anilist_user_id INTEGER NOT NULL UNIQUE,
    anilist_username VARCHAR(100) NOT NULL UNIQUE,
    display_name VARCHAR(40) NOT NULL,
    bio VARCHAR(160) NOT NULL DEFAULT 'Coleccionando historias, un episodio a la vez.',
    avatar_url VARCHAR(1000), banner_url VARCHAR(1000),
    background_color CHAR(7) NOT NULL DEFAULT '#0a0c14',
    surface_color CHAR(7) NOT NULL DEFAULT '#171b29',
    accent_color CHAR(7) NOT NULL DEFAULT '#a88bff',
    dots_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_anilist_sync_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE anilist_connection (
    user_id BIGINT PRIMARY KEY REFERENCES app_user(id) ON DELETE CASCADE,
    access_token TEXT NOT NULL,
    token_expires_at TIMESTAMP,
    connected_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app_session (
    token VARCHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_session_user ON app_session(user_id);
CREATE INDEX idx_session_expiry ON app_session(expires_at);

CREATE TABLE library_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    media_id BIGINT NOT NULL REFERENCES media(id) ON DELETE CASCADE,
    progress INTEGER NOT NULL DEFAULT 0 CHECK (progress >= 0),
    personal_score DECIMAL(3,1) CHECK (personal_score IS NULL OR personal_score BETWEEN 0 AND 10),
    rewatch_count INTEGER NOT NULL DEFAULT 0 CHECK (rewatch_count >= 0),
    tracking_status VARCHAR(32) NOT NULL DEFAULT 'PLANNED' CHECK (tracking_status IN ('PLANNED','IN_PROGRESS','PAUSED','COMPLETED','DROPPED')),
    started_at DATE, completed_at DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, media_id)
);
CREATE INDEX idx_library_user ON library_entries(user_id);

CREATE TABLE activity_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    media_id BIGINT NOT NULL REFERENCES media(id) ON DELETE CASCADE,
    activity_type VARCHAR(16) NOT NULL CHECK (activity_type IN ('ADDED','UPDATED','PROGRESS','REMOVED')),
    previous_progress INTEGER, new_progress INTEGER,
    previous_status VARCHAR(32), new_status VARCHAR(32),
    previous_score DECIMAL(3,1), new_score DECIMAL(3,1),
    previous_rewatch_count INTEGER, new_rewatch_count INTEGER,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_activity_user_created ON activity_history(user_id, created_at DESC);

CREATE TABLE app_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    anilist_notification_id INTEGER NOT NULL,
    notification_type VARCHAR(40) NOT NULL,
    anilist_media_id INTEGER, title VARCHAR(255), cover_image VARCHAR(1000),
    message VARCHAR(1000), episode INTEGER,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    occurred_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, anilist_notification_id)
);
CREATE INDEX idx_notification_user_occurred ON app_notification(user_id, occurred_at DESC);
CREATE INDEX idx_notification_user_read ON app_notification(user_id, is_read);
