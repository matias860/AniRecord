CREATE TABLE weekly_recommendation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    media_id BIGINT NOT NULL REFERENCES media(id) ON DELETE CASCADE,
    week_start DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, week_start)
);

CREATE INDEX idx_weekly_recommendation_week
    ON weekly_recommendation(week_start, created_at DESC);

CREATE INDEX idx_weekly_recommendation_media_week
    ON weekly_recommendation(media_id, week_start);
