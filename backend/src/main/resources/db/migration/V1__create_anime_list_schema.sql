CREATE TABLE app_user (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    display_name VARCHAR(40) NOT NULL DEFAULT 'Mi perfil',
    bio VARCHAR(160) NOT NULL DEFAULT 'Coleccionando historias, un episodio a la vez.',
    avatar_url VARCHAR(1000), banner_url VARCHAR(1000),
    background_color CHAR(7) NOT NULL DEFAULT '#0a0c14',
    surface_color CHAR(7) NOT NULL DEFAULT '#171b29',
    accent_color CHAR(7) NOT NULL DEFAULT '#a88bff',
    dots_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO app_user (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE TABLE anilist_connection (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    access_token TEXT NOT NULL,
    token_expires_at TIMESTAMP,
    username VARCHAR(50) NOT NULL,
    connected_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anilist_id INTEGER NOT NULL UNIQUE,
    media_type VARCHAR(16) NOT NULL CHECK (media_type IN ('ANIME', 'MANGA')),
    title VARCHAR(255) NOT NULL,
    cover_image VARCHAR(1000), banner_image VARCHAR(1000), synopsis TEXT,
    total_units INTEGER CHECK (total_units IS NULL OR total_units >= 0),
    release_start_date DATE, release_end_date DATE,
    release_status VARCHAR(32) CHECK (release_status IS NULL OR release_status IN ('FINISHED', 'RELEASING', 'NOT_YET_RELEASED', 'CANCELLED', 'HIATUS')),
    release_season VARCHAR(16) CHECK (release_season IS NULL OR release_season IN ('WINTER', 'SPRING', 'SUMMER', 'FALL')),
    release_year SMALLINT, last_synced_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE library_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id BIGINT NOT NULL UNIQUE REFERENCES media(id) ON DELETE CASCADE,
    progress INTEGER NOT NULL DEFAULT 0 CHECK (progress >= 0),
    personal_score DECIMAL(3,1) CHECK (personal_score IS NULL OR personal_score BETWEEN 0 AND 10),
    rewatch_count INTEGER NOT NULL DEFAULT 0 CHECK (rewatch_count >= 0),
    tracking_status VARCHAR(32) NOT NULL DEFAULT 'PLANNED' CHECK (tracking_status IN ('PLANNED', 'IN_PROGRESS', 'PAUSED', 'COMPLETED', 'DROPPED')),
    started_at DATE, completed_at DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE activity_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id BIGINT NOT NULL REFERENCES media(id) ON DELETE CASCADE,
    activity_type VARCHAR(16) NOT NULL CHECK (activity_type IN ('ADDED', 'UPDATED', 'PROGRESS', 'REMOVED')),
    previous_progress INTEGER, new_progress INTEGER,
    previous_status VARCHAR(32) CHECK (previous_status IS NULL OR previous_status IN ('PLANNED', 'IN_PROGRESS', 'PAUSED', 'COMPLETED', 'DROPPED')),
    new_status VARCHAR(32) CHECK (new_status IS NULL OR new_status IN ('PLANNED', 'IN_PROGRESS', 'PAUSED', 'COMPLETED', 'DROPPED')),
    previous_score DECIMAL(3,1), new_score DECIMAL(3,1),
    previous_rewatch_count INTEGER, new_rewatch_count INTEGER,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_activity_created_at ON activity_history (created_at);
CREATE INDEX idx_activity_media ON activity_history (media_id);

CREATE TABLE app_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anilist_notification_id INTEGER NOT NULL UNIQUE,
    notification_type VARCHAR(40) NOT NULL CHECK (notification_type IN ('FIRST_EPISODE', 'RELATED_MEDIA_ADDITION', 'MEDIA_DATA_CHANGE', 'MEDIA_MERGE', 'MEDIA_DELETION')),
    anilist_media_id INTEGER, title VARCHAR(255), cover_image VARCHAR(1000),
    message VARCHAR(1000), episode INTEGER,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    occurred_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_notification_occurred ON app_notification (occurred_at);
CREATE INDEX idx_notification_read ON app_notification (is_read);
