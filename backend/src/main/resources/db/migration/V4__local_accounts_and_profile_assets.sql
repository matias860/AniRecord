ALTER TABLE app_user
    ALTER COLUMN anilist_user_id DROP NOT NULL,
    ALTER COLUMN anilist_username DROP NOT NULL;

ALTER TABLE app_user
    ADD COLUMN account_type VARCHAR(16) NOT NULL DEFAULT 'ANILIST',
    ADD COLUMN local_username VARCHAR(30),
    ADD COLUMN password_hash VARCHAR(100);

ALTER TABLE app_user
    ADD CONSTRAINT chk_app_user_account_type
        CHECK (account_type IN ('ANILIST', 'LOCAL')),
    ADD CONSTRAINT chk_app_user_credentials
        CHECK (
            (account_type = 'ANILIST' AND anilist_user_id IS NOT NULL AND anilist_username IS NOT NULL
                AND local_username IS NULL AND password_hash IS NULL)
            OR
            (account_type = 'LOCAL' AND local_username IS NOT NULL AND password_hash IS NOT NULL
                AND anilist_user_id IS NULL AND anilist_username IS NULL)
        );

CREATE UNIQUE INDEX uk_app_user_local_username_lower
    ON app_user (LOWER(local_username))
    WHERE local_username IS NOT NULL;

CREATE TABLE user_profile_asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    asset_type VARCHAR(16) NOT NULL CHECK (asset_type IN ('AVATAR', 'BANNER')),
    content_type VARCHAR(32) NOT NULL,
    data BYTEA NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, asset_type)
);

CREATE INDEX idx_profile_asset_user ON user_profile_asset(user_id);
