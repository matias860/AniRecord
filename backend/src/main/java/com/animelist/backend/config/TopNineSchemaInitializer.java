package com.animelist.backend.config;

import java.sql.Connection;
import javax.sql.DataSource;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/** Keeps the semimonthly 3x3 tables available where Flyway is disabled. */
@Component
@Order(Ordered.HIGHEST_PRECEDENCE + 2)
public class TopNineSchemaInitializer implements ApplicationRunner {
    private static final Logger LOGGER = LoggerFactory.getLogger(TopNineSchemaInitializer.class);
    private final DataSource dataSource;
    private final JdbcTemplate jdbc;

    public TopNineSchemaInitializer(DataSource dataSource, JdbcTemplate jdbc) {
        this.dataSource = dataSource;
        this.jdbc = jdbc;
    }

    @Override
    public void run(ApplicationArguments args) throws Exception {
        try (Connection connection = dataSource.getConnection()) {
            if (!"PostgreSQL".equalsIgnoreCase(connection.getMetaData().getDatabaseProductName())) return;
        }
        jdbc.execute("""
            CREATE TABLE IF NOT EXISTS top_nine_submission (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
                period_start DATE NOT NULL,
                prompt_key VARCHAR(64) NOT NULL,
                published_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT uk_top_nine_user_period UNIQUE(user_id, period_start)
            )
            """);
        jdbc.execute("""
            CREATE TABLE IF NOT EXISTS top_nine_selection (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                submission_id BIGINT NOT NULL REFERENCES top_nine_submission(id) ON DELETE CASCADE,
                media_id BIGINT NOT NULL REFERENCES media(id) ON DELETE CASCADE,
                position SMALLINT NOT NULL CHECK(position BETWEEN 0 AND 8),
                CONSTRAINT uk_top_nine_selection_position UNIQUE(submission_id, position),
                CONSTRAINT uk_top_nine_selection_media UNIQUE(submission_id, media_id)
            )
            """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_top_nine_period ON top_nine_submission(period_start, published_at DESC)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_top_nine_selection_submission ON top_nine_selection(submission_id, position)");
        LOGGER.info("Esquema del 3x3 quincenal verificado correctamente");
    }
}
