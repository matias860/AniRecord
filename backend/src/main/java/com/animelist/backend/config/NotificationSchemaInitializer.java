package com.animelist.backend.config;

import java.sql.Connection;
import javax.sql.DataSource;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * Puente seguro para instalaciones existentes donde Flyway fue desactivado.
 *
 * <p>Solo agrega la estructura de V11 que necesitan las notificaciones locales;
 * todas las sentencias son repetibles y no eliminan datos.</p>
 */
@Component
@Order(Ordered.HIGHEST_PRECEDENCE)
public class NotificationSchemaInitializer implements ApplicationRunner {
    private static final Logger LOGGER = LoggerFactory.getLogger(NotificationSchemaInitializer.class);
    private final DataSource dataSource;
    private final JdbcTemplate jdbc;

    public NotificationSchemaInitializer(DataSource dataSource, JdbcTemplate jdbc) {
        this.dataSource = dataSource;
        this.jdbc = jdbc;
    }

    @Override
    public void run(ApplicationArguments args) throws Exception {
        try (Connection connection = dataSource.getConnection()) {
            String database = connection.getMetaData().getDatabaseProductName();
            if (!"PostgreSQL".equalsIgnoreCase(database)) {
                LOGGER.debug("Se omite la compatibilidad V11 en {}", database);
                return;
            }
        }

        jdbc.execute("ALTER TABLE app_notification ADD COLUMN IF NOT EXISTS source_key VARCHAR(180)");
        jdbc.execute("ALTER TABLE app_notification ALTER COLUMN anilist_notification_id DROP NOT NULL");
        jdbc.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS uk_notification_user_source_key
            ON app_notification(user_id, source_key)
            WHERE source_key IS NOT NULL
            """);
        jdbc.execute("""
            CREATE TABLE IF NOT EXISTS media_relation_watch (
                media_id BIGINT PRIMARY KEY REFERENCES media(id) ON DELETE CASCADE,
                initialized_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                last_checked_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """);
        jdbc.execute("""
            CREATE TABLE IF NOT EXISTS media_relation_snapshot (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                source_media_id BIGINT NOT NULL REFERENCES media(id) ON DELETE CASCADE,
                related_anilist_id INTEGER NOT NULL,
                relation_type VARCHAR(40) NOT NULL,
                related_media_type VARCHAR(16) NOT NULL CHECK (related_media_type IN ('ANIME', 'MANGA')),
                related_format VARCHAR(32),
                related_title VARCHAR(255) NOT NULL,
                related_cover_image VARCHAR(1000),
                first_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT uk_media_relation_snapshot UNIQUE(source_media_id, related_anilist_id, relation_type)
            )
            """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_relation_snapshot_source ON media_relation_snapshot(source_media_id)");
        LOGGER.info("Esquema de notificaciones V11 verificado correctamente");
    }
}
