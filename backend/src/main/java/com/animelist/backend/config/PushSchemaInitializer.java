package com.animelist.backend.config;

import java.sql.Connection;
import javax.sql.DataSource;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/** Additive compatibility bridge for production environments where Flyway is disabled. */
@Component
@Order(Ordered.HIGHEST_PRECEDENCE + 3)
public class PushSchemaInitializer implements ApplicationRunner {
    private static final Logger LOGGER = LoggerFactory.getLogger(PushSchemaInitializer.class);
    private final DataSource dataSource;
    private final JdbcTemplate jdbc;

    public PushSchemaInitializer(DataSource dataSource, JdbcTemplate jdbc) { this.dataSource = dataSource; this.jdbc = jdbc; }

    @Override public void run(ApplicationArguments args) throws Exception {
        try (Connection connection = dataSource.getConnection()) {
            if (!"PostgreSQL".equalsIgnoreCase(connection.getMetaData().getDatabaseProductName())) return;
        }
        jdbc.execute("ALTER TABLE media ADD COLUMN IF NOT EXISTS next_airing_episode INTEGER");
        jdbc.execute("ALTER TABLE media ADD COLUMN IF NOT EXISTS next_airing_at TIMESTAMP WITH TIME ZONE");
        jdbc.execute("ALTER TABLE media ADD COLUMN IF NOT EXISTS last_notified_episode INTEGER");
        jdbc.execute("ALTER TABLE media ADD COLUMN IF NOT EXISTS airing_schedule_checked_at TIMESTAMP WITH TIME ZONE");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_media_next_airing ON media(next_airing_at) WHERE next_airing_at IS NOT NULL");
        jdbc.execute("""
            CREATE TABLE IF NOT EXISTS push_subscription (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
                endpoint TEXT NOT NULL, p256dh_key VARCHAR(180) NOT NULL, auth_key VARCHAR(80) NOT NULL,
                premieres_enabled BOOLEAN NOT NULL DEFAULT TRUE, episodes_enabled BOOLEAN NOT NULL DEFAULT TRUE,
                enabled BOOLEAN NOT NULL DEFAULT TRUE, user_agent VARCHAR(255),
                created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP)
            """);
        jdbc.execute("CREATE UNIQUE INDEX IF NOT EXISTS uk_push_subscription_endpoint ON push_subscription(endpoint)");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_push_subscription_user ON push_subscription(user_id, enabled)");
        jdbc.execute("""
            CREATE TABLE IF NOT EXISTS push_delivery (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                subscription_id BIGINT NOT NULL REFERENCES push_subscription(id) ON DELETE CASCADE,
                notification_id BIGINT NOT NULL REFERENCES app_notification(id) ON DELETE CASCADE,
                status VARCHAR(16) NOT NULL DEFAULT 'PENDING', attempts INTEGER NOT NULL DEFAULT 0,
                last_attempt_at TIMESTAMP WITH TIME ZONE, delivered_at TIMESTAMP WITH TIME ZONE,
                last_error VARCHAR(300), created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT uk_push_delivery UNIQUE(subscription_id, notification_id))
            """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_push_delivery_pending ON push_delivery(status, attempts, created_at)");
        LOGGER.info("Esquema PWA push verificado correctamente");
    }
}
